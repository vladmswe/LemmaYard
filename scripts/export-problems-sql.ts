/**
 * Builds `docs/supabase/problems.sql`: every problem under problems/ as one
 * idempotent script for the Supabase SQL Editor, so the catalog can be seeded
 * without handing anyone a database password. It loads and validates the
 * problems with the importer's own code (`loadProblems`) and writes the same
 * rows `pnpm problems:import` writes (`problemRow`, `testCaseRows`,
 * `collectTagSlugs`, `tagNameFromSlug`, the same number parking); it never
 * prunes.
 *
 * Usage: pnpm problems:export-sql          (rewrite the file)
 *        pnpm problems:export-sql --check  (exit 1 if the committed file is stale)
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { getTableColumns, type Column } from "drizzle-orm";

import { problems, problemTags, tags, testCases } from "@/server/db/schema";
import {
  collectTagSlugs,
  loadProblems,
  NUMBER_PARK_OFFSET,
  problemRow,
  ProblemValidationError,
  tagNameFromSlug,
  testCaseRows,
  type LoadedProblem,
} from "@/server/problems/importer";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const PROBLEMS_DIR = path.join(ROOT, "problems");
export const OUTPUT_FILE = path.join(ROOT, "docs", "supabase", "problems.sql");

/**
 * A dollar-quoted string literal whose tag does not occur in `text`, so no
 * content can end the literal early (works whatever standard_conforming_strings
 * is). Deterministic: `$ly$`, then `$ly1$`, `$ly2$`, ...
 */
export function dollarQuote(text: string): string {
  if (text.includes("\0")) throw new Error("NUL characters cannot be stored in Postgres text");
  for (let i = 0; ; i++) {
    const tag = `$ly${i === 0 ? "" : i}$`;
    // The literal ends at the first `tag` after the opening one.
    if ((text + tag).indexOf(tag) === text.length) return `${tag}${text}${tag}`;
  }
}

/** SQL literal for a value already mapped to its driver form by the column. */
function literal(value: unknown): string {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "boolean") return value ? "TRUE" : "FALSE";
  if (typeof value === "number") {
    if (!Number.isSafeInteger(value)) throw new Error(`unexpected non-integer column value ${value}`);
    return String(value);
  }
  if (typeof value === "string") return dollarQuote(value);
  throw new Error(`unsupported column value of type ${typeof value}`);
}

type Row = Record<string, unknown>;

/** `[column name, SQL literal]` per key, through the Drizzle column (jsonb → JSON text). */
function sqlValues(columns: Record<string, Column>, row: Row): [string, string][] {
  return Object.entries(row).map(([key, value]) => {
    const column = columns[key];
    if (!column) throw new Error(`unknown column key "${key}"`);
    const driver = value === null ? null : column.mapToDriverValue(value);
    const lit = literal(driver);
    return [column.name, column.columnType === "PgJsonb" ? `${lit}::jsonb` : lit];
  });
}

const q = (name: string) => `"${name}"`;
const list = (items: string[]) => items.join(", ");

/** Pure: loaded problems -> script text (no clock, deterministic). */
export function buildProblemsSql(loaded: LoadedProblem[]): string {
  const P = getTableColumns(problems);
  const T = getTableColumns(tags);
  const PT = getTableColumns(problemTags);
  const TC = getTableColumns(testCases);
  const slugs = loaded.map((p) => p.meta.slug);
  const slugList = list(slugs.map(literal));
  const testCount = loaded.reduce((n, p) => n + p.tests.length, 0);
  const tagSlugs = collectTagSlugs(loaded);
  const lines: string[] = [];

  lines.push(
    "-- LemmaYard problem catalog for Supabase (SQL Editor -> New query -> paste -> Run).",
    "-- Generated by `pnpm problems:export-sql` from problems/*; do not edit by hand.",
    `-- Contains ${loaded.length} problems, ${tagSlugs.length} tags and ${testCount} test cases. Run it after`,
    "-- docs/supabase/schema.sql (or `pnpm db:migrate`). It writes the same rows as",
    "-- `pnpm problems:import`: upsert by slug (published), tags, and a full",
    "-- replacement of each problem's tags and test cases, in one transaction.",
    "-- Safe to run again; it never unpublishes problems that are not listed here.",
    "-- NOTE: this file contains the HIDDEN test cases too (is_sample = false). They are",
    "-- public anyway, because problems/*/tests.json is committed to this repository.",
    "",
    "BEGIN;",
    "",
    "-- Refuse to run if another problem in the database already uses one of these numbers.",
    "DO $$",
    "DECLARE taken text;",
    "BEGIN",
    `  SELECT string_agg(${q(P.slug.name)} || ' (' || ${q(P.number.name)} || ')', ', ') INTO taken`,
    `  FROM ${q("problems")}`,
    `  WHERE ${q(P.number.name)} IN (${list(loaded.map((p) => literal(p.meta.number)))})`,
    `    AND ${q(P.slug.name)} NOT IN (${slugList});`,
    "  IF taken IS NOT NULL THEN",
    "    RAISE EXCEPTION 'problem numbers already used by other problems in the database: %', taken;",
    "  END IF;",
    "END $$;",
    "",
    "-- Park the numbers of existing rows so renumbering between them cannot collide;",
    "-- every parked row gets its real number back from the upserts below.",
    `UPDATE ${q("problems")} SET ${q(P.number.name)} = ${q(P.number.name)} + ${NUMBER_PARK_OFFSET}`,
    `WHERE ${q(P.slug.name)} IN (${slugList});`,
    "",
  );

  if (tagSlugs.length > 0) {
    lines.push(
      `INSERT INTO ${q("tags")} (${q(T.slug.name)}, ${q(T.name.name)}) VALUES`,
      tagSlugs.map((slug) => `  (${literal(slug)}, ${literal(tagNameFromSlug(slug))})`).join(",\n"),
      `ON CONFLICT (${q(T.slug.name)}) DO NOTHING;`,
      "",
    );
  }

  for (const problem of loaded) {
    const { meta, tests } = problem;
    const pairs = sqlValues(P, problemRow(problem));
    const slug = literal(meta.slug);
    const idOf = `(SELECT ${q(P.id.name)} FROM ${q("problems")} WHERE ${q(P.slug.name)} = ${slug})`;
    lines.push(
      `-- ---- ${meta.slug} ----`,
      `INSERT INTO ${q("problems")} (${list(pairs.map(([c]) => q(c)))})`,
      `VALUES (${list(pairs.map(([, v]) => v))})`,
      `ON CONFLICT (${q(P.slug.name)}) DO UPDATE SET`,
      [...pairs.map(([c]) => `  ${q(c)} = EXCLUDED.${q(c)}`), `  ${q(P.updatedAt.name)} = now()`].join(",\n") + ";",
      "",
      `DELETE FROM ${q("problem_tags")} WHERE ${q(PT.problemId.name)} = ${idOf};`,
    );
    if (meta.tags.length > 0) {
      lines.push(
        `INSERT INTO ${q("problem_tags")} (${q(PT.problemId.name)}, ${q(PT.tagId.name)})`,
        `SELECT ${idOf}, ${q(T.id.name)} FROM ${q("tags")} WHERE ${q(T.slug.name)} IN (${list(meta.tags.map(literal))});`,
      );
    }
    const caseRows = testCaseRows(tests).map((row) => sqlValues(TC, row));
    lines.push(
      "",
      `DELETE FROM ${q("test_cases")} WHERE ${q(TC.problemId.name)} = ${idOf};`,
      `INSERT INTO ${q("test_cases")} (${list([q(TC.problemId.name), ...caseRows[0].map(([c]) => q(c))])})`,
      `SELECT ${idOf}, v.* FROM (VALUES`,
      caseRows.map((pairs) => `  (${list(pairs.map(([, v]) => v))})`).join(",\n"),
      `) AS v (${list(caseRows[0].map(([c]) => q(c)))})`,
      `ORDER BY v.${q(TC.position.name)};`,
      "",
    );
  }

  lines.push(
    "COMMIT;",
    "",
    `-- Sanity check: expect ${loaded.length} published problems and ${testCount} test cases.`,
    `SELECT count(*) FILTER (WHERE ${q(P.published.name)}) AS published_problems,`,
    `       (SELECT count(*) FROM ${q("test_cases")}) AS test_cases`,
    `FROM ${q("problems")};`,
    "",
  );
  return lines.join("\n");
}

async function main(): Promise<number> {
  const sql = buildProblemsSql(await loadProblems(PROBLEMS_DIR));
  const rel = path.relative(ROOT, OUTPUT_FILE);
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(OUTPUT_FILE, "utf8");
    } catch {
      // missing file counts as stale
    }
    if (current !== sql) {
      console.error(`${rel} is out of date: run \`pnpm problems:export-sql\` and commit it.`);
      return 1;
    }
    console.log(`${rel} is up to date.`);
    return 0;
  }
  mkdirSync(path.dirname(OUTPUT_FILE), { recursive: true });
  writeFileSync(OUTPUT_FILE, sql);
  console.log(`Wrote ${rel} (${sql.length} bytes).`);
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().then(
    (code) => process.exit(code),
    (error: unknown) => {
      if (error instanceof ProblemValidationError) {
        console.error(`problems:export-sql failed:\n${error.errors.map((e) => `  ${e}`).join("\n")}`);
      } else {
        console.error("problems:export-sql failed:", error instanceof Error ? error.message : error);
      }
      process.exit(1);
    },
  );
}
